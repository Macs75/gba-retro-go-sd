#!/usr/bin/env python3
"""gba_hle_wcp_gen.py -- generate Wing Commander: Prophecy's native 3D routines.

  tools/gba_hle_wcp_gen.py <Wing Commander - Prophecy (USA).gba> > src/hle/hle_wcp.inc

Wing Commander: Prophecy (AW9E) draws its 3D (in game, the cutscenes, the
explosions) into a 240-byte-a-line framebuffer of its own and shows it as
tiles; the routines doing it the game copies to IWRAM unchanged (ROM
0x3D7A30 -> 0x03000000):
  - 0x03002860-0x03002938, the span drawer: per span, a 64x64 texture
    walked by packed u/v steps, colour 0 transparent, two pixels a pass
    stored as one halfword, the odd ends a byte each (76% of the game's
    instructions in its real-time 3D cutscene, 2026-11-22);
  - 0x03002230-0x030022D0 and 0x030023C4-0x03002494, the geometry: the
    vertex transform and the projection of a triangle's vertices.
More of its routines decode (see RANGES) but do not fit the ITCM window.

This decodes their words (tools/gba_hle_armgen.py) into C with the
interpreter's exact charges: a checkpoint at each routine's start, every
branch target and return site, and every 16th instruction runs what follows
only when the cycles left exceed the most it can cost, its accesses at the
wait states of the memory the registers point to there (no stop, cycles <= 0
after an instruction, can fall in it), else it returns there and the
interpreter goes on. A return (BX) to one of the edge walkers' call sites
stays native; any other is the interpreter's.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gba_hle_armgen as ag                         # noqa: E402
from gba_hle_armgen import *   # noqa: E402,F401,F403

ROM_OF = 0x3DA290 - 0x2860       # the ROM offset copied to 0x03000000
# each routine's checkpoint bound takes its accesses' wait states from the
# registers that address them at that point (B8/W32: a byte, a word access;
# hle_wcp.cc): the converter's framebuffer (r1) and VRAM (r0) and stack; the
# span drawer's texture (fp) and framebuffer (sl) and stack; the edge
# walkers' work-RAM variables and stack
# All the routines decoded (exact), by index; RANGES is the set that fits
# the ITCM window (5,440 bytes): the span drawer, the transform, the
# projection and the unclipped edge walker's loop, 0x13E0 bytes (the whole
# edge walkers would add ~3.9 KB, the tile converter ~3.6 KB, the
# visibility test ~1.4 KB; 2026-11-22).
ALL = [(0x03002860, 0x03002938, 'WC_MAX(WC_B8(r11), WC_B8(r10))', 'WC_W32(r13)'),   # 0 span drawer
       (0x03002230, 0x030022D0, 'wc_any8', 'wc_any32'),                             # 1 vertex transform
       (0x030023C4, 0x03002494, 'wc_any8', 'wc_any32'),                             # 2 projection
       (0x030022D4, 0x03002350, 'wc_any8', 'wc_any32'),                             # 3 visibility test
       (0x030029D4, 0x03002B34, '0', 'WC_MAX(wc_wram32, WC_W32(r13))'),             # 4 edge walkers
       (0x03001C08, 0x03001D08, '0', 'WC_MAX3(WC_W32(r1), WC_W32(r0), WC_W32(r13))'),  # 5 to tiles
       (0x03002AF0, 0x03002B14, '0', 'WC_MAX(wc_wram32, WC_W32(r13))')]             # 6 its loop only
WC_SET = os.environ.get('WC_ONLY', '0,1,2,6')
RANGES = [ALL[int(i)] for i in WC_SET.split(',')]
EXTRA_ENTRIES = {0x03002AC4}   # the unclipped edge walker, called from outside
K = 16
ag.VRAM_STM = True

rom = open(sys.argv[1], 'rb').read()


def rw(a):
    o = ROM_OF + (a - 0x03000000)
    return struct.unpack('<I', rom[o:o + 4])[0]


words = {}
for lo, hi, eb8, ew32 in RANGES:
    for a in range(lo, hi + 4, 4):
        words[a] = rw(a)
in_range = lambda a: any(r[0] <= a <= r[1] for r in RANGES)
lab = lambda a: 'W_%04x' % (a & 0xFFFF)

targets = set(r[0] for r in RANGES) | {e for e in EXTRA_ENTRIES if in_range(e)}
rets = set()
for a, op in words.items():
    if (op >> 25) & 7 == 5:
        t = b_target(a, op)
        if in_range(t):
            targets.add(t)
        if op & (1 << 24):
            rets.add(a + 4)       # where the callee's BX lr comes back
targets |= rets

out = []
w = out.append
w('/* Generated by tools/gba_hle_wcp_gen.py: do not edit. */')
w('#ifndef WC_CODE')
w('#define WC_LO 0x%08Xu' % RANGES[0][0])
w('#define WC_END 0x%08Xu' % (max(r[1] for r in RANGES) + 4))
# in address order: the hash below is over the words in address order
w('static const u32 wc_ranges[%d][2] = { %s };' % (len(RANGES), ', '.join(
    '{ 0x%08Xu, 0x%08Xu }' % (r[0], r[1] + 4) for r in sorted(RANGES))))
w('#define WC_FNV 0x%08Xu   /* the routines\' words in address order, FNV-1a */' %
  fnv([words[a] for a in sorted(words)]))
w('#else')
w('  switch (pc) {')
for t in sorted(targets):
    w('  case 0x%08Xu: goto %s;' % (t, lab(t)))
w('  default: return (u32)cyc;')
w('  }')
for lo, hi, eb8, ew32 in RANGES:
    addrs = list(range(lo, hi + 4, 4))
    cps = set()
    run = 0
    for a in addrs:
        if a in targets or run == K:
            cps.add(a)
            run = 0
        run += 1
    live = live_flags(words, addrs, cps)
    cl = sorted(cps)
    for a in addrs:
        if a in cps:
            nxt = next((c for c in cl if c > a), hi + 4)
            seg = [x for x in addrs if a <= x < nxt]
            if a in targets:
                w('%s:' % lab(a))
            # a taken branch adds BT before the next checkpoint guards the rest
            nbr = sum(1 for x in seg if (words[x] >> 25) & 7 == 5 or (words[x] & 0x0FFFFFF0) == 0x012FFF10)
            wst = seg_worst(words, seg, None).replace('0 * BT', '%d * BT' % nbr)
            wst = wst.replace('* b8', '* (%s)' % eb8).replace('* w32', '* (%s)' % ew32)
            w('  if (cyc <= %s) EXIT(0x%08Xu);' % (wst, a))
            w('  cyc -= %d * F;' % len(seg))
            seg_end = nxt
        rem = sum(1 for x in addrs if a <= x < seg_end)
        w('  %s' % decode(a, words[a], in_range, lab, live=live[a], rem=rem, ret_targets=rets))
    w('  EXIT(0x%08Xu);' % (hi + 4))
w('#endif')
print('\n'.join(out))
